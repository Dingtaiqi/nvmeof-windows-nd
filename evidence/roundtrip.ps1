# roundtrip.ps1 - the acceptance test: 1 MiB of seeded random bytes written to
# the remote disk's NTFS volume, read back, and compared byte for byte (SHA-256
# of the bytes as generated vs. SHA-256 of the bytes read back).  The same seed
# and the same generator are used on every run, so two reports can be compared.
#
# NOTE: the size parameter is $Length, not $Bytes.  PowerShell variable names are
# case-insensitive, so a [int]$Bytes parameter also type-constrains a local
# $bytes, and "New-Object byte[] $Bytes" then silently leaves an Int32 behind
# (found the hard way on the first run of this script).

param(
    [string]$Path = 'Z:\roundtrip.bin',
    [int]$Length = 1048576,
    [int]$Seed = 20261017,
    [string]$Out = 'D:\rdma\nvmeof\evidence\roundtrip_result.txt'
)

Add-Content -Path $Out -Value ('=== roundtrip ' + (Get-Date -Format 'yyyy-MM-dd HH:mm:ss')) -Encoding ASCII

$data = [byte[]]::new($Length)
$rng = New-Object System.Random $Seed
$rng.NextBytes($data)
$sha = [System.Security.Cryptography.SHA256]::Create()
$memHash = [BitConverter]::ToString($sha.ComputeHash($data)).Replace('-', '')

Add-Content -Path $Out -Value ('generated bytes={0} seed={1} memHash={2}' -f $Length, $Seed, $memHash) -Encoding ASCII

$sw = [Diagnostics.Stopwatch]::StartNew()
try
{
    [IO.File]::WriteAllBytes($Path, $data)
    $writeMs = $sw.ElapsedMilliseconds
    $len = (Get-Item $Path).Length
    $sw.Restart()
    $back = [IO.File]::ReadAllBytes($Path)
    $readMs = $sw.ElapsedMilliseconds
    $fileHash = [BitConverter]::ToString($sha.ComputeHash($back)).Replace('-', '')

    $diff = -1
    if ($back.Length -ne $data.Length)
    {
        Add-Content -Path $Out -Value ('LENGTH MISMATCH read={0} written={1}' -f $back.Length, $data.Length) -Encoding ASCII
    }
    else
    {
        for ($i = 0; $i -lt $data.Length; $i++)
        {
            if ($back[$i] -ne $data[$i]) { $diff = $i; break }
        }
    }

    Add-Content -Path $Out -Value ('written={0} length={1} writeMs={2} readMs={3}' -f $Path, $len, $writeMs, $readMs) -Encoding ASCII
    Add-Content -Path $Out -Value ('fileHash={0}' -f $fileHash) -Encoding ASCII
    if ($diff -lt 0 -and $fileHash -eq $memHash) { Add-Content -Path $Out -Value 'RESULT PASS byte-exact round trip' -Encoding ASCII }
    elseif ($diff -ge 0) { Add-Content -Path $Out -Value ('RESULT FAIL first differing byte at offset {0} (mem 0x{1:X2} file 0x{2:X2})' -f $diff, $data[$diff], $back[$diff]) -Encoding ASCII }
    else { Add-Content -Path $Out -Value 'RESULT FAIL hashes differ' -Encoding ASCII }
}
catch
{
    Add-Content -Path $Out -Value ('RESULT FAIL exception after {0} ms: {1}' -f $sw.ElapsedMilliseconds, $_.Exception.Message) -Encoding ASCII
}
